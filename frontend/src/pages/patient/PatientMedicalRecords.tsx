import React, { useState, useEffect } from 'react';
import { Layout } from '../../components/Layout';
import { FolderHeart, Plus, ExternalLink, Download } from 'lucide-react';
import api from '../../services/api';
import { MedicalRecord } from '../../types';

const exportRecordToPdf = async (rec: MedicalRecord) => {
  const { jsPDF } = await import('jspdf');
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
  const pageWidth = 210;
  const margin = 18;
  const contentWidth = pageWidth - margin * 2;

  // Header
  doc.setFillColor(2, 132, 199);
  doc.rect(0, 0, pageWidth, 34, 'F');
  doc.setFillColor(13, 148, 136);
  doc.rect(0, 30, pageWidth, 4, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(18);
  doc.setFont('helvetica', 'bold');
  doc.text('🏥 MediCare · Medical Record Summary', margin, 14);
  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.text(`Record Type: ${rec.recordType}  ·  Date: ${rec.recordDate}`, margin, 23);

  let y = 46;

  // Title
  doc.setTextColor(15, 23, 42);
  doc.setFontSize(18);
  doc.setFont('helvetica', 'bold');
  doc.text(rec.title, margin, y);
  y += 10;

  // Patient info box
  doc.setFillColor(240, 249, 255);
  doc.roundedRect(margin, y, contentWidth, 20, 3, 3, 'F');
  doc.setFontSize(8); doc.setFont('helvetica', 'bold');
  doc.setTextColor(2, 100, 164);
  doc.text('PATIENT INFORMATION', margin + 4, y + 7);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10); doc.setTextColor(15, 23, 42);
  doc.text(`Name: ${rec.patient.user.fullName}`, margin + 4, y + 14);
  doc.text(`Blood Group: ${rec.patient.bloodGroup || 'N/A'}`, margin + 90, y + 14);
  y += 28;

  // Doctor info (if linked)
  if (rec.doctor) {
    doc.setFontSize(10); doc.setFont('helvetica', 'normal'); doc.setTextColor(71, 85, 105);
    doc.text(`Linked Doctor: Dr. ${rec.doctor.user.fullName} (${rec.doctor.specialization})`, margin, y);
    y += 8;
  }

  // Notes
  if (rec.notes) {
    y += 4;
    doc.setFillColor(254, 249, 195);
    const noteLines = doc.splitTextToSize(rec.notes, contentWidth - 10);
    const noteH = noteLines.length * 5.5 + 14;
    doc.roundedRect(margin, y, contentWidth, noteH, 3, 3, 'F');
    doc.setDrawColor(245, 158, 11);
    doc.line(margin, y, margin, y + noteH);
    doc.setFontSize(8); doc.setFont('helvetica', 'bold'); doc.setTextColor(120, 80, 0);
    doc.text('NOTES / FINDINGS', margin + 5, y + 8);
    doc.setFont('helvetica', 'normal'); doc.setFontSize(10); doc.setTextColor(69, 40, 0);
    doc.text(noteLines, margin + 5, y + 14);
    y += noteH + 8;
  }

  // File URL
  if (rec.fileUrl) {
    y += 4;
    doc.setFontSize(9); doc.setFont('helvetica', 'bold'); doc.setTextColor(2, 132, 199);
    doc.text('Document Reference:', margin, y);
    doc.setFont('helvetica', 'normal'); doc.setTextColor(71, 85, 105);
    doc.text(rec.fileUrl, margin, y + 6);
    y += 16;
  }

  // Footer
  doc.setFillColor(248, 250, 252);
  doc.rect(0, 282, pageWidth, 15, 'F');
  doc.setTextColor(148, 163, 184); doc.setFontSize(8); doc.setFont('helvetica', 'normal');
  doc.text(`Generated by MediCare · ${new Date().toLocaleDateString('en-IN')}`, pageWidth / 2, 289, { align: 'center' });

  doc.save(`medical-record-${rec.id}-${rec.title.replace(/\s+/g, '_')}.pdf`);
};

export const PatientMedicalRecords: React.FC = () => {
  const [records, setRecords] = useState<MedicalRecord[]>([]);
  const [showModal, setShowModal] = useState(false);
  const [exporting, setExporting] = useState<number | null>(null);

  // Form states
  const [title, setTitle] = useState('');
  const [recordType, setRecordType] = useState('Lab Report');
  const [fileUrl, setFileUrl] = useState('');
  const [notes, setNotes] = useState('');
  const [recordDate, setRecordDate] = useState(new Date().toISOString().split('T')[0]);

  useEffect(() => {
    fetchRecords();
  }, []);

  const fetchRecords = async () => {
    try {
      const res = await api.get('/medical-records/my');
      setRecords(res.data.data || []);
    } catch (err) {
      console.error(err);
    }
  };

  const handlePdfExport = async (rec: MedicalRecord) => {
    setExporting(rec.id);
    try {
      await exportRecordToPdf(rec);
    } finally {
      setExporting(null);
    }
  };

  const handleAddRecord = async (e: React.FormEvent) => {
    e.preventDefault();
    try {
      await api.post('/medical-records', {
        title,
        recordType,
        fileUrl,
        notes,
        recordDate,
      });
      setShowModal(false);
      setTitle('');
      setFileUrl('');
      setNotes('');
      fetchRecords();
    } catch (err) {
      console.error(err);
    }
  };

  return (
    <Layout title="Medical Records & Reports" subtitle="Securely store and access your diagnostic reports, X-rays, and clinical history">
      <div style={{ display: 'flex', justifyContent: 'flex-end', marginBottom: '24px' }}>
        <button onClick={() => setShowModal(true)} className="btn btn-primary">
          <Plus size={18} /> Upload New Health Record
        </button>
      </div>

      <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fill, minmax(320px, 1fr))', gap: '24px' }}>
        {records.map((rec) => (
          <div key={rec.id} className="card">
            <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', marginBottom: '12px' }}>
              <span style={{ fontSize: '11px', fontWeight: 800, color: '#0284c7', backgroundColor: 'var(--primary-light)', padding: '3px 8px', borderRadius: '4px' }}>
                {rec.recordType}
              </span>
              <span style={{ fontSize: '12px', color: 'var(--text-secondary)' }}>{rec.recordDate}</span>
            </div>

            <h3 style={{ fontSize: '17px', fontWeight: 700, color: 'var(--text-primary)', marginBottom: '8px' }}>{rec.title}</h3>

            {rec.notes && (
              <p style={{ fontSize: '13px', color: 'var(--text-secondary)', backgroundColor: 'var(--bg-main)', padding: '10px', borderRadius: '8px', marginBottom: '16px' }}>
                {rec.notes}
              </p>
            )}

            {rec.doctor && (
              <div style={{ fontSize: '12px', color: 'var(--text-secondary)', marginBottom: '16px' }}>
                Linked Doctor: <strong>Dr. {rec.doctor.user.fullName}</strong>
              </div>
            )}

            <div style={{ display: 'flex', gap: '8px', marginTop: 'auto' }}>
              {rec.fileUrl && (
                <a href={rec.fileUrl} target="_blank" rel="noreferrer" className="btn btn-outline btn-sm" style={{ flex: 1, justifyContent: 'center' }}>
                  <ExternalLink size={14} /> Open File
                </a>
              )}
              <button
                onClick={() => handlePdfExport(rec)}
                className="btn btn-primary btn-sm"
                style={{ flex: 1 }}
                disabled={exporting === rec.id}
              >
                <Download size={14} />
                {exporting === rec.id ? 'Exporting...' : 'Export PDF'}
              </button>
            </div>
          </div>
        ))}
      </div>

      {records.length === 0 && (
        <div className="card empty-state">
          <FolderHeart className="empty-state-icon" size={48} />
          <h3>No medical records uploaded</h3>
          <p>Click "Upload New Health Record" to add your lab results, X-rays, or medical reports.</p>
        </div>
      )}

      {/* Add Record Modal */}
      {showModal && (
        <div className="modal-overlay">
          <div className="modal-content">
            <div className="modal-header">
              <h3 style={{ fontSize: '18px', fontWeight: 700 }}>Upload New Medical Record</h3>
              <button onClick={() => setShowModal(false)} style={{ border: 'none', cursor: 'pointer' }}>×</button>
            </div>

            <form onSubmit={handleAddRecord}>
              <div className="modal-body">
                <div className="form-group">
                  <label className="form-label">Record Title *</label>
                  <input type="text" className="form-input" placeholder="e.g. Blood Test Report, Chest X-Ray" value={title} onChange={(e) => setTitle(e.target.value)} required />
                </div>

                <div className="form-grid">
                  <div className="form-group">
                    <label className="form-label">Record Type *</label>
                    <select className="form-select" value={recordType} onChange={(e) => setRecordType(e.target.value)}>
                      <option value="Lab Report">Lab Report</option>
                      <option value="X-Ray / Scan">X-Ray / Scan</option>
                      <option value="Vaccination Certificate">Vaccination Certificate</option>
                      <option value="Hospital Discharge Summary">Hospital Discharge Summary</option>
                      <option value="Other">Other</option>
                    </select>
                  </div>
                  <div className="form-group">
                    <label className="form-label">Record Date *</label>
                    <input type="date" className="form-input" value={recordDate} onChange={(e) => setRecordDate(e.target.value)} required />
                  </div>
                </div>

                <div className="form-group">
                  <label className="form-label">Document File URL (Drive/S3 Link)</label>
                  <input type="url" className="form-input" placeholder="https://drive.google.com/..." value={fileUrl} onChange={(e) => setFileUrl(e.target.value)} />
                </div>

                <div className="form-group">
                  <label className="form-label">Notes / Findings Summary</label>
                  <textarea className="form-textarea" rows={3} placeholder="Add doctor observations or test values..." value={notes} onChange={(e) => setNotes(e.target.value)} />
                </div>
              </div>

              <div className="modal-footer">
                <button type="button" onClick={() => setShowModal(false)} className="btn btn-outline">Cancel</button>
                <button type="submit" className="btn btn-primary">Save Medical Record</button>
              </div>
            </form>
          </div>
        </div>
      )}
    </Layout>
  );
};
